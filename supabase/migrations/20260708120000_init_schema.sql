-- Core schema for the personal finance app (profiles, categories, movements,
-- recurring templates, goals).
--
-- Design decisions worth noting:
--   * `amount` is always stored as a POSITIVE magnitude. Whether a movement is
--     income, an expense, or an investment is derived from its category `type`.
--     This keeps the 5-tier model authoritative and avoids sign-convention bugs.
--   * `categories.user_id` is nullable: NULL rows are global/system defaults
--     visible to everyone (read-only), non-NULL rows are user-created custom
--     categories. This is a strict superset of the PRD schema and is what the
--     "New Categories" screen needs.
--   * `user_id` columns default to `auth.uid()` so the client never has to send
--     it and RLS can never be tricked into writing to another user.
-- =============================================================================

create extension if not exists "pgcrypto";      -- gen_random_uuid()

-- ---------- Enumerated types -------------------------------------------------
create type public.category_type as enum (
  'income_fixed',
  'income_variable',
  'expense_essential',
  'expense_personal',
  'expense_leisure',
  'investment'
);

create type public.recurrence_frequency as enum ('weekly', 'monthly', 'yearly');

create type public.goal_status as enum ('active', 'achieved', 'paused');

-- ---------- profiles ---------------------------------------------------------
create table public.profiles (
  id                    uuid primary key references auth.users (id) on delete cascade,
  display_name          text,
  currency              text          not null default 'EUR',
  monthly_budget_limit  numeric(14,2) not null default 0,   -- target for the burn-rate bar
  created_at            timestamptz   not null default now()
);

-- ---------- categories -------------------------------------------------------
create table public.categories (
  id          bigint generated always as identity primary key,
  user_id     uuid references public.profiles (id) on delete cascade,   -- NULL => global default
  name        text          not null,
  type        public.category_type not null,
  icon        text,                                    -- icon key resolved by the client
  color       text,                                    -- hex string used by the client
  created_at  timestamptz   not null default now()
);

create index categories_user_id_idx on public.categories (user_id);

-- ---------- movements --------------------------------------------------------
create table public.movements (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid          not null default auth.uid() references public.profiles (id) on delete cascade,
  category_id   bigint        not null references public.categories (id),
  concept       text          not null default '',
  amount        numeric(14,2) not null check (amount >= 0),  -- magnitude; direction comes from category.type
  date          date          not null default current_date,
  is_recurring  boolean       not null default false,
  template_id   uuid,                                        -- set when generated by the recurring engine
  tags          text[]        not null default '{}',
  created_at    timestamptz   not null default now()
);

create index movements_user_date_idx on public.movements (user_id, date desc);
create index movements_category_idx  on public.movements (category_id);
create index movements_tags_idx      on public.movements using gin (tags);
create index movements_template_idx  on public.movements (template_id);

-- ---------- recurring_templates ---------------------------------------------
create table public.recurring_templates (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid          not null default auth.uid() references public.profiles (id) on delete cascade,
  category_id         bigint        not null references public.categories (id),
  concept             text          not null default '',
  amount              numeric(14,2) not null check (amount >= 0),
  frequency           public.recurrence_frequency not null default 'monthly',
  billing_day         int           not null check (billing_day between 1 and 31),
  last_executed_date  date,
  is_active           boolean       not null default true,
  created_at          timestamptz   not null default now()
);

create index recurring_templates_user_idx on public.recurring_templates (user_id);

-- Link auto-generated movements back to their template (added after the table
-- exists so the FK can reference it).
alter table public.movements
  add constraint movements_template_fk
  foreign key (template_id) references public.recurring_templates (id) on delete set null;

-- ---------- financial_goals --------------------------------------------------
create table public.financial_goals (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid          not null default auth.uid() references public.profiles (id) on delete cascade,
  title          text          not null,
  target_amount  numeric(14,2) not null check (target_amount > 0),
  current_amount numeric(14,2) not null default 0 check (current_amount >= 0),
  target_date    date,
  status         public.goal_status not null default 'active',
  created_at     timestamptz   not null default now()
);

create index financial_goals_user_idx on public.financial_goals (user_id);

